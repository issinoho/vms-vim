#!/usr/bin/env python3
"""gen_kit.py <runtime-dir> <kit-dir> - the runtime part of the PCSI kit.

Writes, for the ~5,400 files of Vim's runtime tree:
  <kit-dir>/runtime.pdf      directory and file lines for the product description;
                             each file gets a unique flat material name, because
                             PCSI looks material up by name in one directory
  <kit-dir>/KIT_MATERIAL.VIM run by MAKE_KIT.COM: copies each file to its material
                             name with filecopy() (one Vim run, not 5,400 COPYs)
  <kit-dir>/VIM$CASE.VIM     run by VIM$STARTUP.COM INSTALL: PCSI stores names in
                             upper case, this renames every file and directory
                             under VIM$ROOT:[VIM92] back to its real name
The runtime installs in [VIM.VIM92] (VIMRUNTIME).  docs/NOTES.md N17.
"""
import os
import sys

# Characters an ODS-5 name needs to escape with "^" in a VMS file spec
# (besides the dots, handled below).
SPECIAL = set(' !#&\'()+,;=@[]^`{}~%')
# ... of which PCSI's product description takes none: "^(" is %PCSI-E-PDFIVS.
# Files whose names have them are left out of the kit (NOTES N19).
PCSI_UNSAFE = SPECIAL


def vms_name(name):
    """A file name as an ODS-5 VMS spec: interior dots escaped, a type always."""
    out = ''.join('^' + c if c in SPECIAL else c for c in name)
    head, dot, ext = out.rpartition('.')
    if not dot:
        return out + '.'
    return head.replace('.', '^.') + '.' + ext


def vms_dir(parts):
    for p in parts:
        if '.' in p or any(c in SPECIAL for c in p):
            sys.exit('gen_kit: directory name needs escaping, not handled: %s' % p)
    return ''.join('.' + p for p in parts)


def vimstr(s):
    return "'" + s.replace("'", "''") + "'"


def main():
    rt, kit = sys.argv[1], sys.argv[2]
    dirs, files, left_out = [], [], []
    for top, dnames, fnames in os.walk(rt):
        dnames.sort()
        rel = os.path.relpath(top, rt)
        parts = [] if rel == '.' else rel.split(os.sep)
        if parts:
            dirs.append(parts)
        for f in sorted(fnames):
            if any(c in PCSI_UNSAFE for c in f):
                left_out.append('/'.join(parts + [f]))
                continue
            files.append((parts, f))

    with open(os.path.join(kit, 'runtime.pdf'), 'w') as pdf:
        pdf.write('    directory [VIM.VIM92] ;\n')
        for parts in dirs:
            pdf.write('    directory [VIM.VIM92%s] ;\n' % vms_dir(parts).upper())
        for i, (parts, f) in enumerate(files, 1):
            pdf.write('    file [VIM.VIM92%s]%s source [000000]R%05d.DAT ;\n'
                      % (vms_dir(parts).upper(), vms_name(f).upper(), i))

    with open(os.path.join(kit, 'KIT_MATERIAL.VIM'), 'w') as m:
        m.write('" Generated by tools/gen_kit.py: copy the runtime to its material names.\n'
                '" MAKE_KIT.COM defines VIMKIT_RT ([.RUNTIME]) and VIMKIT_MAT.\n'
                'let s:root = $VIMKIT_RT[: -2]\n'
                'let s:mat = $VIMKIT_MAT\n'
                'let s:bad = []\n'
                'let s:n = 0\n'
                'func s:C(dir, name, mat)\n'
                "  let from = s:root .. a:dir .. ']' .. a:name\n"
                '  if !filecopy(from, s:mat .. a:mat)\n'
                '    call add(s:bad, from)\n'
                '  endif\n'
                '  let s:n += 1\n'
                'endfunc\n')
        for i, (parts, f) in enumerate(files, 1):
            m.write("call s:C(%s, %s, 'R%05d.DAT')\n" % (vimstr(vms_dir(parts)),
                                                     vimstr(vms_name(f)), i))
        m.write('if empty(s:bad)\n'
                "  call writefile(['MAKE_KIT: copied ' .. s:n .. ' runtime files'],"
                " '[.VMS.KIT]KIT_MATERIAL.OK')\n"
                'else\n'
                "  call writefile(s:bad, '[.VMS.KIT]KIT_MATERIAL.ERR')\n"
                'endif\n'
                'qa!\n')

    with open(os.path.join(kit, 'VIM$CASE.VIM'), 'w') as c:
        c.write('" Generated by tools/gen_kit.py; run by VIM$STARTUP.COM INSTALL.\n'
                '" PCSI installs the runtime with upper-case names: give each file and\n'
                '" directory under VIM$ROOT:[VIM92] its real name again.\n'
                "let s:root = 'VIM$ROOT:[VIM92'\n"
                'let s:bad = []\n'
                'func s:R(dir, name, suffix)\n'
                "  let d = s:root .. a:dir .. ']'\n"
                '  if rename(d .. toupper(a:name) .. a:suffix, d .. a:name .. a:suffix) != 0\n'
                '    call add(s:bad, d .. a:name .. a:suffix)\n'
                '  endif\n'
                'endfunc\n')
        for parts, f in files:
            n = vms_name(f)
            if n != n.upper():
                c.write("call s:R(%s, %s, '')\n" % (vimstr(vms_dir(parts)), vimstr(n)))
        # Directories last, deepest first (names are looked up without case, so
        # renaming a parent does not disturb its children's paths).
        for parts in sorted(dirs, key=len, reverse=True):
            if parts[-1] != parts[-1].upper():
                c.write("call s:R(%s, %s, '.DIR')\n" % (vimstr(vms_dir(parts[:-1])),
                                                       vimstr(parts[-1])))
        c.write('if !empty(s:bad)\n'
                "  call writefile(s:bad, 'SYS$SCRATCH:VIM$CASE.ERR')\n"
                'endif\n'
                'qa!\n')
    print('gen_kit: %d directories, %d files' % (len(dirs), len(files)))
    for f in left_out:
        print('gen_kit: left out (PCSI cannot name it): %s' % f)


if __name__ == '__main__':
    main()
